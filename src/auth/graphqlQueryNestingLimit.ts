import { Lexer, Source, TokenKind } from 'graphql'
import { headersWithCors, type PayloadRequest, type SanitizedConfig } from 'payload'

/**
 * Maximum lexical nesting accepted before the GraphQL parser runs.
 *
 * The repository's generated Admin GraphQL documents have at most 15 nested selection sets at
 * the configured Admin depth of 5. This ceiling is over 66 times that measured maximum and is
 * aligned with the application's existing complexity threshold for deeply nested field chains.
 * It also bounds recursive parsing of nested input values; exceptionally deep custom argument or
 * inline-fragment structures beyond this limit are not generated by the Admin UI.
 */
export const MAX_GRAPHQL_QUERY_NESTING = 1_000

const nestingErrorMessage = `GraphQL query nesting exceeds the maximum supported nesting of ${MAX_GRAPHQL_QUERY_NESTING} levels.`

type RouteHandler = (request: Request) => Promise<Response>

/** Match graphql-http 1.23.1's POST response media-type negotiation. */
function getAcceptedGraphQLResponseType(request: Request): string | null {
  const acceptedTypes = (request.headers.get('accept') || '*/*')
    .replace(/\s/g, '')
    .toLowerCase()
    .split(',')

  for (const acceptedType of acceptedTypes) {
    const [mediaType, ...parameters] = acceptedType.split(';')
    const charset =
      parameters.find((parameter) => parameter.includes('charset=')) ?? 'charset=utf-8'

    if (mediaType === 'application/graphql-response+json' && charset === 'charset=utf-8') {
      return 'application/graphql-response+json; charset=utf-8'
    }
    if (
      (mediaType === 'application/json' || mediaType === 'application/*' || mediaType === '*/*') &&
      (charset === 'charset=utf-8' || charset === 'charset=utf8')
    ) {
      return 'application/json; charset=utf-8'
    }
  }

  return null
}

type ClosingToken = typeof TokenKind.BRACE_R | typeof TokenKind.BRACKET_R | typeof TokenKind.PAREN_R

/**
 * Measure GraphQL delimiter nesting iteratively. Returns null for malformed lexical/delimiter
 * input so graphql-http can report the normal GraphQL.js parse error.
 */
export function measureGraphQLQueryNesting(query: string): number | null {
  const closingTokens: ClosingToken[] = []
  let maximumNesting = 0

  try {
    const lexer = new Lexer(new Source(query))
    for (let token = lexer.advance(); token.kind !== TokenKind.EOF; token = lexer.advance()) {
      switch (token.kind) {
        case TokenKind.BRACE_L:
          closingTokens.push(TokenKind.BRACE_R)
          break
        case TokenKind.BRACKET_L:
          closingTokens.push(TokenKind.BRACKET_R)
          break
        case TokenKind.PAREN_L:
          closingTokens.push(TokenKind.PAREN_R)
          break
        case TokenKind.BRACE_R:
        case TokenKind.BRACKET_R:
        case TokenKind.PAREN_R:
          // Let GraphQL.js report malformed delimiter order through its normal parse error.
          if (closingTokens.pop() !== token.kind) return null
          break
      }

      maximumNesting = Math.max(maximumNesting, closingTokens.length)
      if (maximumNesting > MAX_GRAPHQL_QUERY_NESTING) return maximumNesting
    }
  } catch {
    // Invalid lexical input remains graphql-http's responsibility; this guard only bounds nesting.
    return null
  }

  return maximumNesting
}

/**
 * Reject deeply nested JSON GraphQL POST documents before graphql-http invokes GraphQL.js's
 * recursive parser. Compose inside `withGraphQLRequestBodyLimit` so inspection is byte-bounded.
 */
export function withGraphQLQueryNestingLimit(
  config: Promise<SanitizedConfig> | SanitizedConfig,
  handler: RouteHandler,
): RouteHandler {
  const configPromise = Promise.resolve(config)

  return async (request) => {
    const responseContentType = getAcceptedGraphQLResponseType(request)
    if (!responseContentType) return handler(request)

    const [mediaType, charset = 'charset=utf-8'] = (request.headers.get('content-type') ?? '')
      .replace(/\s/g, '')
      .toLowerCase()
      .split(';')
    if (mediaType !== 'application/json' || charset !== 'charset=utf-8') return handler(request)

    let query: unknown
    try {
      const body: unknown = await request.clone().json()
      if (body && typeof body === 'object' && !Array.isArray(body)) {
        query = (body as Record<string, unknown>).query
      }
    } catch {
      // Preserve graphql-http's existing response for malformed JSON bodies.
      return handler(request)
    }

    const nesting = typeof query === 'string' ? measureGraphQLQueryNesting(query) : null
    if (nesting === null || nesting <= MAX_GRAPHQL_QUERY_NESTING) return handler(request)

    const resolvedConfig = await configPromise
    const headers = headersWithCors({
      headers: new Headers({
        'Cache-Control': 'no-store',
        'Content-Type': responseContentType,
        Vary: 'Origin',
      }),
      req: {
        headers: request.headers,
        payload: { config: resolvedConfig } as unknown as PayloadRequest['payload'],
      },
    })

    return new Response(JSON.stringify({ errors: [{ message: nestingErrorMessage }] }), {
      headers,
      status: 400,
    })
  }
}
