import type { JobTask } from '../types'

/**
 * Publishes drafts whose `publishAt` has arrived (CNT: drafts, versions and scheduled publishing).
 *
 * Editors keep writing an article as a draft and set *Publish at*; this task flips `_status` to
 * `published` once that moment has passed. It runs on the daily cron, so a scheduled article goes
 * live within a day of its time — Vercel Hobby allows one cron run per day. Running it by hand from
 * Admin › Scheduled jobs publishes immediately, which is what the job page is for.
 *
 * Articles saved later than their own `publishAt` are picked up too (the editor scheduled a time in
 * the past by mistake); anything without the field is left alone.
 */
export const publishScheduled: JobTask = {
  slug: 'publish-scheduled',
  label: 'Publish scheduled articles',
  description:
    'Publishes draft articles whose Publish at time has passed. The daily cron checks once a day; run it by hand to publish immediately.',
  schedule: 'daily',
  estimate: 'under 5 s',
  async run({ payload, log }) {
    const now = new Date().toISOString()
    const published: string[] = []

    // Page through while publishing: each update removes the document from the next query.
    for (;;) {
      const { docs } = await payload.find({
        collection: 'articles',
        // Drafts only: published documents have nothing to do.
        draft: true,
        where: {
          and: [
            { _status: { equals: 'draft' } },
            { publishAt: { less_than_equal: now } },
            { deletedAt: { exists: false } },
          ],
        },
        limit: 50,
        depth: 0,
        sort: 'publishAt',
        overrideAccess: true,
      })
      if (docs.length === 0) break

      for (const doc of docs) {
        // Publishing merges `data` over the *published* document, not over the draft. Passing the
        // draft's own values (minus the bookkeeping fields) is what makes this publish the draft
        // rather than the stale published copy plus a new status.
        const data = { ...(doc as unknown as Record<string, unknown>) }
        const id = data.id as number | string
        // Bookkeeping fields are regenerated by Payload; sending them back is noise.
        for (const field of ['id', 'createdAt', 'updatedAt', '_status']) delete data[field]
        await payload.update({
          collection: 'articles',
          id,
          data: { ...data, _status: 'published' },
          draft: false,
          overrideAccess: true,
          context: { skipAudit: false, scheduledPublish: true },
        })
        published.push(String((doc as { slug?: string | null }).slug ?? doc.id))
        log(`Published ${(doc as { title?: string }).title ?? doc.id}`)
      }
    }

    const summary =
      published.length === 0
        ? 'No draft was due to publish.'
        : `Published ${published.length} scheduled article${published.length === 1 ? '' : 's'}.`
    log(summary)
    return { summary, details: { checkedAt: now, published } }
  },
}
