#!/usr/bin/env node
/**
 * Writes src/styles/admin/nav-icons.css: one Lucide icon per sidebar link, as a CSS mask keyed to
 * Payload's stable nav ids (#nav-<slug>, #nav-global-<slug>). Payload's nav markup stays untouched.
 *
 *   node scripts/generate-nav-icons.mjs        (also part of `pnpm generate:all`)
 *
 * To give a new collection or global an icon, add it to NAV_ICONS and rerun.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as lucide from 'lucide-react'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'

/** Nav id -> Lucide component name. */
const NAV_ICONS = {
  'nav-articles': 'FileText',
  'nav-projects': 'FolderKanban',
  'nav-services': 'Wrench',
  'nav-media': 'Images',
  'nav-header': 'PanelTop',
  'nav-about': 'UserRound',
  'nav-experiences': 'BriefcaseBusiness',
  'nav-educations': 'GraduationCap',
  'nav-skills': 'Gauge',
  'nav-certificates': 'Award',
  'nav-global-footer': 'PanelBottom',
  'nav-users': 'Users',
  'nav-view-site': 'ExternalLink',
  'nav-ui-kit': 'Palette',
}
const FALLBACK = 'File'

const svg = (name) => {
  const Icon = lucide[name]
  if (!Icon) throw new Error(`Unknown Lucide icon: ${name}`)
  const markup = renderToStaticMarkup(createElement(Icon, { size: 24, strokeWidth: 2 }))
    .replace(/ class="[^"]*"/, '')
    .replace('currentColor', '#000')
  return `url("data:image/svg+xml,${encodeURIComponent(markup).replace(/'/g, '%27')}")`
}

const lines = [
  '/* Generated by scripts/generate-nav-icons.mjs. Do not edit; change NAV_ICONS and rerun. */',
  '@layer payload {',
  `  .nav__link { --nav-icon: ${svg(FALLBACK)}; }`,
  ...Object.entries(NAV_ICONS).map(([id, name]) => `  #${id} { --nav-icon: ${svg(name)}; }`),
  '}',
  '',
]

const out = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/styles/admin/nav-icons.css',
)
fs.writeFileSync(out, lines.join('\n'))
console.log(`Wrote ${path.relative(process.cwd(), out)} (${Object.keys(NAV_ICONS).length} icons)`)
