#!/usr/bin/env node
/**
 * Writes src/styles/admin/nav-icons.css: one Lucide icon per sidebar link, as a CSS mask keyed to
 * Payload's stable nav ids (#nav-<slug>, #nav-global-<slug>). Payload's nav markup stays untouched.
 *
 *   node scripts/generate-nav-icons.mjs        (also part of `pnpm generate:all`)
 *
 * To give a new collection or global an icon and a colour, add it to NAV_ICONS and rerun.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as lucide from 'lucide-react'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'

/**
 * Nav id -> [Lucide component name, tone]. Tones are theme tokens (`--nav-tone-*` in tokens.css)
 * with light and dark values: amber, orange, rose, violet, blue, teal, green, slate.
 */
const NAV_ICONS = {
  'nav-articles': ['FileText', 'amber'],
  'nav-projects': ['FolderKanban', 'blue'],
  'nav-services': ['Wrench', 'teal'],
  'nav-media': ['Images', 'violet'],
  'nav-header': ['PanelTop', 'slate'],
  'nav-about': ['UserRound', 'rose'],
  'nav-experiences': ['BriefcaseBusiness', 'orange'],
  'nav-educations': ['GraduationCap', 'blue'],
  'nav-skills': ['Gauge', 'green'],
  'nav-certificates': ['Award', 'amber'],
  'nav-global-site-settings': ['SlidersHorizontal', 'violet'],
  'nav-global-navigation': ['Compass', 'blue'],
  'nav-global-footer': ['PanelBottom', 'slate'],
  'nav-redirects': ['ArrowRightLeft', 'teal'],
  'nav-users': ['Users', 'teal'],
  'nav-roles': ['KeyRound', 'orange'],
  'nav-audit-logs': ['ScrollText', 'amber'],
  'nav-view-site': ['ExternalLink', 'slate'],
  'nav-system': ['Activity', 'teal'],
  'nav-database': ['Database', 'green'],
  'nav-jobs': ['CalendarClock', 'blue'],
  'nav-terminal': ['Terminal', 'amber'],
  'nav-gallery': ['Component', 'rose'],
}
/** Sidebar group (admin.group label) -> [Lucide component name, tone]; matched by Payload's group id. */
const NAV_GROUP_ICONS = {
  Content: ['LayoutGrid', 'amber'],
  Profile: ['IdCard', 'blue'],
  'Site settings': ['Settings2', 'violet'],
  Admin: ['ShieldCheck', 'teal'],
}

const FALLBACK = 'File'

const svg = (name) => {
  const Icon = lucide[name]
  if (!Icon) throw new Error(`Unknown Lucide icon: ${name}`)
  const markup = renderToStaticMarkup(createElement(Icon, { size: 24, strokeWidth: 2 }))
    .replace(/ class="[^"]*"/, '')
    .replace('currentColor', '#000')
  return `url("data:image/svg+xml,${encodeURIComponent(markup).replace(/'/g, '%27')}")`
}

const lines = [
  '/* Generated by scripts/generate-nav-icons.mjs. Do not edit; change NAV_ICONS and rerun. */',
  '@layer payload {',
  `  .nav__link { --nav-icon: ${svg(FALLBACK)}; }`,
  ...Object.entries(NAV_ICONS).map(
    ([id, [name, tone]]) =>
      `  #${id} { --nav-icon: ${svg(name)}; --nav-icon-color: var(--nav-tone-${tone}); }`,
  ),
  ...Object.entries(NAV_GROUP_ICONS).map(
    ([group, [name, tone]]) =>
      `  [id='nav-group-${group}'] { --nav-group-icon: ${svg(name)}; --nav-group-color: var(--nav-tone-${tone}); }`,
  ),
  '}',
  '',
]

const out = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/styles/admin/nav-icons.css',
)
fs.writeFileSync(out, lines.join('\n'))
console.log(
  `Wrote ${path.relative(process.cwd(), out)} (${Object.keys(NAV_ICONS).length} items, ${Object.keys(NAV_GROUP_ICONS).length} groups)`,
)
