import { chromium } from '@playwright/test'
const browser = await chromium.launch({ executablePath: '/tmp/chromium', args: ['--no-sandbox'] })
const page = await (await browser.newContext()).newPage()
await page.goto('http://localhost:3000/admin/login')
await page.fill('#field-email', 'dev@payloadcms.com')
await page.fill('#field-password', 'test')
await page.click('button[type="submit"]')
await page.waitForURL('**/admin')
await page.goto('http://localhost:3000/admin/collections/articles/create')
await page.waitForLoadState('networkidle')
const inner = await page.locator('#field-publishedAt').evaluate((el) => el.outerHTML.slice(0, 1500))
console.log(inner)
await page.locator('#field-publishedAt input').first().click()
await page.waitForTimeout(500)
console.log('--- open picker buttons:', await page.locator('.react-datepicker button, .date-time-picker button, button.react-datepicker__navigation').evaluateAll((els) => els.map((e) => `${e.getAttribute('aria-label') ?? ''}|${e.textContent?.trim()}`).join(' ; ')))
console.log('--- today link:', await page.locator('text=Today').count())
await browser.close()
